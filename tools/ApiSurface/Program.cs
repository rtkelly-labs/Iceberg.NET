using System.Text.Json;
using System.Xml.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

if (args.Length is < 2 or > 3 || args[0] is not ("check" or "update"))
{
    Console.Error.WriteLine("Usage: ApiSurface check|update <repo-root> [Debug|Release]");
    return 2;
}
var update = args[0] == "update";
var root = Path.GetFullPath(args[1]);
var config = args.Length == 3 ? args[2] : "Debug";
var output = Path.Combine(root, "docs", "api");
Directory.CreateDirectory(output);
var defaultTfm = XDocument.Load(Path.Combine(root, "Directory.Build.props")).Descendants("TargetFramework").Single().Value;
var projects = XDocument.Load(Path.Combine(root, "Iceberg.Net.slnx")).Descendants("Project")
    .Select(p => (string)p.Attribute("Path")!).Where(p => p.StartsWith("src/", StringComparison.Ordinal));
var assemblies = projects.SelectMany(project =>
{
    var file = Path.Combine(root, project);
    var properties = XDocument.Load(file);
    var tfms = properties.Descendants("TargetFrameworks").FirstOrDefault()?.Value
        ?? properties.Descendants("TargetFramework").FirstOrDefault()?.Value ?? defaultTfm;
    return tfms.Split(';').Select(tfm => (Name: Path.GetFileNameWithoutExtension(project), Tfm: tfm,
        File: Path.Combine(Path.GetDirectoryName(file)!, "bin", config, tfm, Path.GetFileNameWithoutExtension(project) + ".dll")));
}).ToList();
foreach (var missing in assemblies.Where(a => !File.Exists(a.File)))
    throw new FileNotFoundException("Build the full solution before checking API contracts", missing.File);
var expectedFiles = assemblies.Select(a => $"{a.Name}.{a.Tfm}.txt").ToHashSet(StringComparer.Ordinal);
foreach (var stale in Directory.GetFiles(output, "*.txt").Where(p => !expectedFiles.Contains(Path.GetFileName(p))))
{
    if (update) File.Delete(stale);
    else throw new InvalidOperationException($"Stale API snapshot: {stale}; review the project/target removal");
}
var references = ((string?)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES") ?? "").Split(Path.PathSeparator)
    .Concat(PackageReferences())
    .Concat(assemblies.Where(a => a.Tfm == "net10.0").Select(a => a.File))
    .Where(File.Exists).DistinctBy(Path.GetFileName, StringComparer.OrdinalIgnoreCase).Select(p => MetadataReference.CreateFromFile(p)).ToList();
var format = new SymbolDisplayFormat(
    typeQualificationStyle: SymbolDisplayTypeQualificationStyle.NameAndContainingTypesAndNamespaces,
    genericsOptions: SymbolDisplayGenericsOptions.IncludeTypeParameters | SymbolDisplayGenericsOptions.IncludeTypeConstraints | SymbolDisplayGenericsOptions.IncludeVariance,
    memberOptions: SymbolDisplayMemberOptions.IncludeType | SymbolDisplayMemberOptions.IncludeModifiers | SymbolDisplayMemberOptions.IncludeParameters |
        SymbolDisplayMemberOptions.IncludeContainingType | SymbolDisplayMemberOptions.IncludeConstantValue | SymbolDisplayMemberOptions.IncludeExplicitInterface,
    parameterOptions: SymbolDisplayParameterOptions.IncludeType | SymbolDisplayParameterOptions.IncludeName | SymbolDisplayParameterOptions.IncludeDefaultValue |
        SymbolDisplayParameterOptions.IncludeParamsRefOut,
    propertyStyle: SymbolDisplayPropertyStyle.ShowReadWriteDescriptor,
    miscellaneousOptions: SymbolDisplayMiscellaneousOptions.UseSpecialTypes | SymbolDisplayMiscellaneousOptions.EscapeKeywordIdentifiers |
        SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);
var failed = false;
foreach (var assembly in assemblies.OrderBy(a => a.Name, StringComparer.Ordinal).ThenBy(a => a.Tfm, StringComparer.Ordinal))
{
    var target = MetadataReference.CreateFromFile(assembly.File);
    var compilation = CSharpCompilation.Create("ApiSurface", references: references.Where(r => Path.GetFileName(r.FilePath) != assembly.Name + ".dll").Append(target));
    var symbol = (IAssemblySymbol)compilation.GetAssemblyOrModuleSymbol(target)!;
    var lines = new List<string>();
    VisitNamespace(symbol.GlobalNamespace);
    var text = $"# {assembly.Name} ({assembly.Tfm})\n# Generated by tools/ApiSurface; changes require API review.\n" + string.Join("\n", lines.Order(StringComparer.Ordinal)) + "\n";
    var path = Path.Combine(output, $"{assembly.Name}.{assembly.Tfm}.txt");
    if (update) File.WriteAllText(path, text);
    else if (!File.Exists(path) || File.ReadAllText(path).Replace("\r\n", "\n", StringComparison.Ordinal) != text)
    {
        Console.Error.WriteLine($"API surface changed: {Path.GetRelativePath(root, path)}. Review it, then regenerate with ApiSurface update.");
        failed = true;
    }
    Console.WriteLine($"{assembly.Name} {assembly.Tfm}: {lines.Count} declarations");

    void VisitNamespace(INamespaceSymbol ns)
    {
        foreach (var nested in ns.GetNamespaceMembers()) VisitNamespace(nested);
        foreach (var type in ns.GetTypeMembers()) VisitType(type);
    }
    void VisitType(INamedTypeSymbol type)
    {
        if (!Exported(type)) return;
        var bases = new[] { type.BaseType }.Where(t => t is not null && t.SpecialType != SpecialType.System_Object)
            .Cast<ITypeSymbol>().Concat(type.Interfaces).Select(t => t.ToDisplayString(format)).Order(StringComparer.Ordinal);
        lines.Add($"{type.DeclaredAccessibility} {(type.IsStatic ? "static " : (type.IsAbstract ? "abstract " : "") + (type.IsSealed ? "sealed " : ""))}{(type.IsReadOnly ? "readonly " : "")}{(type.IsRefLikeType ? "ref " : "")}{type.TypeKind} {type.ToDisplayString(format)}" +
            (bases.Any() ? " : " + string.Join(", ", bases) : ""));
        foreach (var member in type.GetMembers())
        {
            if (member is INamedTypeSymbol nested) { VisitType(nested); continue; }
            if (!Exported(member) || member is IMethodSymbol { MethodKind: MethodKind.PropertyGet or MethodKind.PropertySet or MethodKind.EventAdd or MethodKind.EventRemove }) continue;
            lines.Add(member.DeclaredAccessibility + " " + member.ToDisplayString(format));
        }
    }
}
return failed ? 1 : 0;

IEnumerable<string> PackageReferences()
{
    foreach (var file in Directory.GetFiles(Path.Combine(root, "src"), "project.assets.json", SearchOption.AllDirectories))
    {
        using var doc = JsonDocument.Parse(File.ReadAllText(file));
        var assets = doc.RootElement;
        foreach (var target in assets.GetProperty("targets").EnumerateObject())
        foreach (var lib in target.Value.EnumerateObject())
        {
            if (!lib.Value.TryGetProperty("compile", out var compile) ||
                !assets.GetProperty("libraries").TryGetProperty(lib.Name, out var metadata) ||
                !metadata.TryGetProperty("path", out var path)) continue;
            foreach (var folder in assets.GetProperty("packageFolders").EnumerateObject())
            foreach (var item in compile.EnumerateObject())
                if (item.Name.EndsWith(".dll", StringComparison.Ordinal))
                    yield return Path.Combine(folder.Name, path.GetString()!, item.Name);
        }
    }
}

static bool Exported(ISymbol s) => s.DeclaredAccessibility is Accessibility.Public or Accessibility.Protected or Accessibility.ProtectedOrInternal;
