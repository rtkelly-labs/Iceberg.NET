using System.ComponentModel.DataAnnotations;
using Microsoft.EntityFrameworkCore;
using Iceberg.Net.Catalog;

namespace Iceberg.Net.EntityFrameworkCore.Tests;

public enum OrderStatus { Open = 1, Shipped = 2, Cancelled = 3 }

public sealed class Order
{
    public long Id { get; set; }
    public string Customer { get; set; } = "";
    public int Qty { get; set; }
    public decimal Amount { get; set; }
    public OrderStatus Status { get; set; }
    public DateTime CreatedAt { get; set; }
    public string? Note { get; set; }

    /// <summary>Computed: not a column.</summary>
    public string Label => $"{Customer}#{Id}";
}

public sealed class Customer
{
    [Key] public string Name { get; set; } = "";
    public string Region { get; set; } = "";
    /// <summary>A row version: generated by the provider on every save, checked on update and delete.</summary>
    [Timestamp] public long Version { get; set; }
}

/// <summary>A user-managed concurrency token.</summary>
public sealed class Account
{
    public Guid Id { get; set; }
    public decimal Balance { get; set; }
    [ConcurrencyCheck] public string Stamp { get; set; } = "";
}

public class ShopContext(DbContextOptions options) : DbContext(options)
{
    public DbSet<Order> Orders => Set<Order>();
    public DbSet<Customer> Customers => Set<Customer>();
    public DbSet<Account> Accounts => Set<Account>();

    protected override void OnModelCreating(ModelBuilder b)
    {
        b.UseIcebergSnakeCaseNames();
        b.Entity<Order>(o =>
        {
            o.ToIcebergTable("orders");
            o.Property(x => x.Amount).HasPrecision(12, 2);
            o.HasIcebergPartition(x => x.CreatedAt, "day");
            o.Ignore(x => x.Label);
        });
        b.Entity<Account>().Property(x => x.Balance).HasIcebergType("decimal(18, 2)");
    }
}

/// <summary>A fresh in-memory catalog (on a temp warehouse) per test.</summary>
public abstract class EfTest : IDisposable
{
    private readonly string _warehouse = Path.Combine(Path.GetTempPath(), "iceberg-dotnet-efcore", Guid.NewGuid().ToString("N"));

    protected EfTest() : this(w => new InMemoryCatalog(w)) { }

    /// <param name="create">Builds the catalog over the test's warehouse (a subclass with hooks, say).</param>
    protected EfTest(Func<string, InMemoryCatalog> create) => Catalog = create(_warehouse);

    protected InMemoryCatalog Catalog { get; }
    protected static readonly Namespace Ns = Namespace.Of("shop");

    protected ShopContext NewContext(Action<Infrastructure.IcebergDbContextOptionsBuilder>? configure = null) =>
        new(new DbContextOptionsBuilder<ShopContext>().UseIceberg(Catalog, Ns, configure).Options);

    protected async Task<ShopContext> CreatedAsync()
    {
        var ctx = NewContext();
        await ctx.Database.EnsureCreatedAsync();
        return ctx;
    }

    protected Task<Table> TableAsync(string name) => Catalog.LoadTableAsync(TableIdentifier.Of("shop", name));

    protected static List<Order> SampleOrders(int n = 30) => Enumerable.Range(1, n).Select(i => new Order
    {
        Id = i,
        Customer = new[] { "alice", "bob", "carol" }[i % 3],
        Qty = i % 7,
        Amount = i * 2.5m,
        Status = (OrderStatus)(i % 3 + 1),
        CreatedAt = new DateTime(2026, 1, 1).AddDays(i % 5).AddHours(i),
        Note = i % 4 == 0 ? null : $"n{i}",
    }).ToList();

    protected async Task<List<Order>> SeedOrdersAsync(int n = 30)
    {
        await using var ctx = await CreatedAsync();
        var orders = SampleOrders(n);
        ctx.Orders.AddRange(orders);
        await ctx.SaveChangesAsync();
        return orders;
    }

    public void Dispose()
    {
        Catalog.Dispose();
        if (Directory.Exists(_warehouse)) Directory.Delete(_warehouse, recursive: true);
        GC.SuppressFinalize(this);
    }
}
